const GUEST_LIMIT = Number(env('AI_GUEST_DAILY_LIMIT', '5'));

const admin = createClient(env('SUPABASE_URL'), env('SUPABASE_SERVICE_ROLE_KEY'), { auth: { persistSession: false, autoRefreshToken: false } });

function corsHeaders(origin) {
  return {
    'Access-Control-Allow-Origin': ALLOWED.includes(origin) ? origin : ALLOWED[0] || '*',
    'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
    'Access-Control-Allow-Methods': 'POST, OPTIONS',
    Vary: 'Origin',
  };
}

/* ---------------- Daily current affairs (Gemini + Google Search grounding) ---------------- */
// One digest per day (IST), generated by the first visitor of the day and cached in public.daily_news for everyone.
// It doesn't count towards anyone's AI allowance.
const NEWS_CATEGORIES = ['Polity & Governance', 'Economy', 'International Relations', 'Environment & Ecology', 'Science & Technology', 'Society & Welfare', 'Security & Defence', 'Geography & Places', 'History & Culture', 'Schemes & Reports'];
const istDay = (offsetDays = 0) => new Date(Date.now() + 5.5 * 3600e3 + offsetDays * 864e5).toISOString().slice(0, 10);

function newsPrompt(day) {
  const long = new Date(`${day}T12:00:00Z`).toLocaleDateString('en-IN', { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
  return `Today is ${long} (India). Use Google Search to find the most important news of the last 24–36 hours that matters for the UPSC Civil Services Examination.
Prioritise: PIB releases, government schemes and policies, Supreme Court and High Court judgments, Parliament and new laws, constitutional bodies, RBI, budget and economic data, international relations and summits, environment, species and protected areas, science, space and defence technology, reports and indices, places in news, art and culture.
Skip: celebrity, entertainment, crime, sports results and party-political news unless they have a clear UPSC angle.
Every fact must come from the search results. Do not invent numbers, dates or names; if unsure, leave it out.
Write 12–16 items, each from a different story, plus 5–8 "UPSC Essentials": key terms or concepts in today's news, explained the way the Indian Express UPSC Essentials does.
Reply with ONLY one JSON object (no markdown, no commentary) in exactly this shape:
{"theme":"one line summing up the day for an aspirant","items":[{"title":"","category":"one of: ${NEWS_CATEGORIES.join(' | ')}","gs":"GS-I | GS-II | GS-III | GS-IV","summary":"2–3 factual sentences","upscAngle":"why it matters for UPSC and the static syllabus link","prelimsFacts":["",""],"mainsQuestion":"one probable Mains question","keywords":["",""],"source":"publication name"}],"essentials":[{"term":"","explanation":"2–3 sentences"}]}`;
}

function parseLooseJSON(text) {
  const cleaned = String(text || '').replace(/^```(?:json)?\s*/i, '').replace(/```\s*$/, '').trim();
  try { return JSON.parse(cleaned); } catch {}
  const m = cleaned.match(/\{[\s\S]*\}/);
  if (m) return JSON.parse(m[0]);
  throw new Error('Unreadable news digest');
}

function cleanDigest(d) {
  const s = (v, n) => String(v ?? '').trim().slice(0, n);
  const arr = (v, n, m = 400) => (Array.isArray(v) ? v : []).map((x) => s(x, m)).filter(Boolean).slice(0, n);
  const items = (Array.isArray(d?.items) ? d.items : [])
    .map((it) => ({
      title: s(it?.title, 220),
      category: NEWS_CATEGORIES.includes(it?.category) ? it.category : 'Polity & Governance',
      gs: /^GS-(I|II|III|IV)$/.test(it?.gs) ? it.gs : '',
      summary: s(it?.summary, 900),
      upscAngle: s(it?.upscAngle, 700),
      prelimsFacts: arr(it?.prelimsFacts, 5),
      mainsQuestion: s(it?.mainsQuestion, 400),
      keywords: arr(it?.keywords, 8, 60),
      source: s(it?.source, 80),
    }))
    .filter((it) => it.title && it.summary)
    .slice(0, 20);
  const essentials = (Array.isArray(d?.essentials) ? d.essentials : [])
    .map((e) => ({ term: s(e?.term, 120), explanation: s(e?.explanation, 700) }))
    .filter((e) => e.term && e.explanation)
    .slice(0, 10);
  return { theme: s(d?.theme, 300), items, essentials };
}

async function generateDigest(key, day) {
  let last;
  for (const m of GEMINI_AUTO_CHAIN) {
    const res = await fetch(`${GEMINI_BASE}/models/${m}:generateContent`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'x-goog-api-key': key },
      body: JSON.stringify({
        systemInstruction: { parts: [{ text: 'You are the current-affairs editor of a UPSC coaching institute. You are accurate, neutral and concise, and you reply with valid JSON only.' }] },
        contents: [{ role: 'user', parts: [{ text: newsPrompt(day) }] }],
        tools: [{ google_search: {} }],
        generationConfig: { temperature: 0.3 },
      }),
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok) {
      last = new Error(`${m} ${res.status}: ${data?.error?.message || ''}`);
      console.warn('[news]', last.message);
      if (isModelUnavailable(res.status, data?.error?.message) || res.status === 429 || res.status >= 500) continue;
      throw last;
    }
    const cand = data?.candidates?.[0];
    const text = (cand?.content?.parts || []).filter((p) => !p.thought).map((p) => p.text || '').join('');
    const digest = cleanDigest(parseLooseJSON(text));
    if (digest.items.length < 4) { last = new Error('Too few news items'); continue; }
    const gm = cand?.groundingMetadata || {};
    const seen = new Set();
    const sources = (gm.groundingChunks || [])
      .map((c) => ({ title: String(c?.web?.title || '').slice(0, 120), uri: String(c?.web?.uri || '') }))
      .filter((x) => /^https:\/\//.test(x.uri) && !seen.has(x.title + x.uri) && seen.add(x.title + x.uri))
      .slice(0, 40);
    return { digest: { ...digest, model: m }, sources, searchHtml: String(gm.searchEntryPoint?.renderedContent || '') };
  }
  throw last || new Error('Could not compile the news');
}

async function handleNews(body, reply) {
  const today = istDay();
  const day = /^\d{4}-\d{2}-\d{2}$/.test(body?.day || '') ? body.day : today;
  const days = async () => {
    const { data } = await admin.from('daily_news').select('day').eq('status', 'ready').order('day', { ascending: false }).limit(30);
    return (data || []).map((r) => r.day);
  };
  const ready = async (row) => reply(200, { status: 'ready', day: row.day, data: row.data, sources: row.sources || [], searchHtml: row.search_html || '', days: await days() });

  const { data: row, error } = await admin.from('daily_news').select('*').eq('day', day).maybeSingle();
  if (error) return reply(500, { error: 'News storage is not set up (run supabase/schema.sql).' });
  if (row?.status === 'ready') return ready(row);
  if (day !== today) return reply(200, { status: 'missing', day, days: await days() });

  const age = row ? Date.now() - Date.parse(row.updated_at) : Infinity;
  if (row?.status === 'generating' && age < 180e3) return reply(200, { status: 'generating', day, days: await days() });
  if (row?.status === 'failed' && age < 600e3) return reply(200, { status: 'failed', day, error: row.error || '', days: await days() });

  // Claim today's slot so only one request generates it.
  const now = new Date().toISOString();
  if (!row) {
    const { error: e } = await admin.from('daily_news').insert({ day, status: 'generating', updated_at: now });
    if (e) return reply(200, { status: 'generating', day, days: await days() });
  } else {
    const { data: claimed } = await admin.from('daily_news').update({ status: 'generating', updated_at: now, error: null }).eq('day', day).eq('updated_at', row.updated_at).select('day');
    if (!claimed?.length) return reply(200, { status: 'generating', day, days: await days() });
  }

  try {
    const { digest, sources, searchHtml } = await generateDigest(env('GEMINI_API_KEY'), day);
    const { data: saved, error: e } = await admin.from('daily_news')
      .update({ status: 'ready', data: digest, sources, search_html: searchHtml, error: null, updated_at: new Date().toISOString() })
      .eq('day', day).select('*').single();
    if (e) throw e;
    return ready(saved);
  } catch (e) {
    console.error('news generation failed', e);
    await admin.from('daily_news').update({ status: 'failed', error: String(e.message || e).slice(0, 300), updated_at: new Date().toISOString() }).eq('day', day);
    return reply(200, { status: 'failed', day, error: 'Could not compile today\'s current affairs right now. Please try again in a few minutes.', days: await days() });
  }
}

Deno.serve(async (req) => {
  const origin = (req.headers.get('origin') || '').replace(/\/+$/, '');
  const headers = { ...corsHeaders(origin), 'Content-Type': 'application/json' };
  const reply = (status, body) => new Response(JSON.stringify(body), { status, headers });

  if (req.method === 'OPTIONS') return new Response('ok', { headers });
  if (req.method !== 'POST') return reply(405, { error: 'Method not allowed' });
  if (!ALLOWED.includes(origin)) return reply(403, { error: 'Forbidden' });

  const provider = env('GEMINI_API_KEY') ? 'gemini' : env('OPENAI_API_KEY') ? 'openai' : null;
  if (!provider) return reply(501, { error: 'Server AI is not configured' });
  const key = provider === 'gemini' ? env('GEMINI_API_KEY') : env('OPENAI_API_KEY');
  const model = provider === 'gemini' ? env('GEMINI_MODEL', 'auto') : env('OPENAI_MODEL', 'gpt-4o-mini');

  let body = {};
  try { body = await req.json(); } catch {}
  if (body?.action === 'news') {
    if (!env('GEMINI_API_KEY')) return reply(501, { error: 'Current affairs need GEMINI_API_KEY (Google Search grounding).' });
    return handleNews(body, reply);
  }
  let messages;
  try {
    messages = buildMessages(body?.task, body?.params || {});
  } catch (e) {
    return reply(400, { error: e.message });
  }

  // Who is asking: a signed-in user (by id) or a guest (by IP).
  let userId = null;
  const token = (req.headers.get('authorization') || '').replace(/^Bearer\s+/i, '');
  if (token && token.split('.').length === 3) {
    try {
      const { data } = await admin.auth.getUser(token);
      userId = data?.user?.id || null;
    } catch {}
  }
  const ip = (req.headers.get('x-forwarded-for') || '').split(',')[0].trim() || 'unknown';
  const limit = userId ? USER_LIMIT : GUEST_LIMIT;
  let used = 0;
  const usageKey = userId ? `u:${userId}` : `ip:${ip}`;
  const { data: n, error } = await admin.rpc('bump_ai_usage', { p_key: usageKey });
  if (error) console.error('bump_ai_usage failed (did you run supabase/schema.sql?)', error.message);
  else used = n;
  if (used > limit) {
    return reply(429, {
      used: limit,
      limit,
      error: userId
        ? `You've used today's ${limit} free AI requests. They reset at midnight (IST), or add your own free Gemini key in Settings for unlimited use.`
        : `Guests get ${limit} free AI requests a day. Sign in with Google (Profile page) to get ${USER_LIMIT} a day.`,
    });
  }

  try {
    const content = await callAI({ provider, key, model, messages });
    return reply(200, { content, used, limit });
  } catch (e) {
    // A failed request doesn't count towards the daily allowance.
    if (used > 0) {
      const { error: re } = await admin.rpc('refund_ai_usage', { p_key: usageKey });
      if (re) console.error('refund_ai_usage failed (did you run supabase/schema.sql?)', re.message);
      else used -= 1;
    }
    if (e.code === 'RATE') return reply(429, { used, limit, error: 'The free AI is busy right now. Please try again in a few minutes, or add your own free Gemini key in Settings.' });
    if (e.code === 'BLOCKED') return reply(422, { used, limit, error: AI_MESSAGES.BLOCKED });
    if (e.code === 'TIMEOUT' || e.code === 'LENGTH') return reply(504, { used, limit, error: AI_MESSAGES[e.code] });
    console.error('AI call failed', e.code, e.message);
    return reply(502, { used, limit, error: AI_MESSAGES.API });
  }
});
