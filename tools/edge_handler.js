const env = (k, d = '') => Deno.env.get(k) || d;
const ALLOWED = env('ALLOWED_ORIGINS', 'https://youriasbuddy.com,https://www.youriasbuddy.com,https://raushanraj358.github.io,http://localhost:5173')
  .split(',')
